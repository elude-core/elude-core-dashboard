/**
 * Coordonnées [lon, lat] des villes de la zone business (Europe + Maghreb) —
 * Umami (MaxMind) ne remonte que le NOM de la ville, pas ses coordonnées.
 * Clé normalisée : minuscules + accents retirés (les libellés MaxMind varient).
 * Ville absente de la table → le visiteur retombe sur le dot pays (centroïde),
 * rien n'est perdu. Précision ~0,1° (≈1 px au zoom actuel) : villes majeures
 * uniquement, pas de communes de banlieue (elles retombent sur le pays).
 */

function norm(s: string): string {
  return s.toLowerCase().normalize("NFD").replace(/[̀-ͯ]/g, "").replace(/['’-]/g, " ").replace(/\s+/g, " ").trim();
}

